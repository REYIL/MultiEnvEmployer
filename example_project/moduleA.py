def typer(n):
    """Возвращает разные типы данных"""
    types_map = {
        1: "string",
        2: 123,
        3: [1, 2, 3],
        4: (1, 2, 3),
        5: {1, 2, 3},
        6: {"key": "value"},
        7: True,
        8: None
    }
    return types_map.get(n)


# =============================================================================
# БОЛЬШИЕ ДАННЫЕ
# =============================================================================
def giga_data(n):
    """Генерирует большие объемы данных для тестирования streaming"""
    if n == 1:
        # Большая строка
        return "text" * 500000
    elif n == 2:
        # Большой список
        return ["text"] * 500000
    elif n == 3:
        # Большой tuple
        return ("text",) * 500000
    else:
        return None


