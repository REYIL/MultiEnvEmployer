def add(a, b):
    """Сложение двух чисел"""
    return a + b


def multiply(a, b):
    """Умножение двух чисел"""
    return a * b


def non():
    """Функция без return"""
    pass


# =============================================================================
# PRINT
# =============================================================================
def tt(n):
    """Вызывает print n раз"""
    for i in range(n):
        print(f"Print iteration {i + 1}")


# =============================================================================
# ГЕНЕРАТОРЫ
# =============================================================================
def stream_numbers(n):
    """Генератор чисел от 0 до n-1"""
    for i in range(n):
        yield i


# =============================================================================
# ASYNC ФУНКЦИИ
# =============================================================================
async def async_operation(x):
    """Асинхронная операция"""
    await asyncio.sleep(0.1)
    return x * 2


# =============================================================================
# STATEFUL
# =============================================================================
_state = None


def set_state(value):
    """Сохраняет значение в модуле"""
    global _state
    _state = value


def get_state():
    """Возвращает сохраненное значение"""
    return _state


